create table if not exists public.catalogo_juegos (
    id bigint generated by default as identity primary key,
    nombre text not null,
    tipo text not null constraint catalogo_juegos_tipo_check check (
        tipo in (
            'Juegos de estrategia',
            'Juegos de conquista',
            'Juegos en equipo',
            'Juegos de party',
            'Juegos de mentir',
            'Juegos de cartas sencillos',
            'Destreza y rapidez'
        )
    ),
    descripcion text,
    jugadores_min integer not null check (jugadores_min >= 1),
    jugadores_max integer not null check (jugadores_max >= jugadores_min),
    dificultad text not null constraint catalogo_juegos_dificultad_check check (
        dificultad in ('Principiante', 'Conocedor', 'Sabio')
    ),
    duracion_minutos integer not null check (duracion_minutos > 0),
    foto_url text,
    created_at timestamptz not null default now()
);

create table if not exists public.menu (
    id bigint generated by default as identity primary key,
    nombre text not null,
    categoria text not null,
    descripcion text,
    precio numeric(10,2) not null check (precio >= 0),
    foto_url text,
    created_at timestamptz not null default now()
);

create table if not exists public.tienda (
    id bigint generated by default as identity primary key,
    nombre text not null,
    tipo text not null constraint tienda_tipo_check check (
        tipo in (
            'Juegos de estrategia',
            'Juegos de conquista',
            'Juegos en equipo',
            'Juegos de party',
            'Juegos de mentir',
            'Juegos de cartas sencillos',
            'Destreza y rapidez'
        )
    ),
    descripcion text,
    jugadores_min integer not null check (jugadores_min >= 1),
    jugadores_max integer not null check (jugadores_max >= jugadores_min),
    dificultad text not null constraint tienda_dificultad_check check (
        dificultad in ('Principiante', 'Conocedor', 'Sabio')
    ),
    duracion_minutos integer not null check (duracion_minutos > 0),
    precio numeric(10,2) not null check (precio >= 0),
    stock integer not null default 0 check (stock >= 0),
    foto_url text,
    created_at timestamptz not null default now()
);

